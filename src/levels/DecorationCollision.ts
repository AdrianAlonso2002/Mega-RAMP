/** Shared by the editor checkbox and the physical level builder. */
export function decorationHasCollision(object: LevelObjectData): boolean {
  return object.properties?.hasCollision !== undefined
    ? Boolean(object.properties.hasCollision)
    : solidDefaults.has(String(object.properties?.subType ?? "tree"));
}
